#!/usr/bin/env python3
"""Build the exported GKI with fresh output, anonymous identity and new signing keys."""
from pathlib import Path
import argparse,os,subprocess,json,datetime,hashlib
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--pipeline',type=Path,default=root/'.deps/gki');p.add_argument('--out',type=Path,required=True);p.add_argument('--dist',type=Path,required=True);p.add_argument('--jobs',type=int,default=6);args=p.parse_args()
pipeline=args.pipeline.resolve();out=args.out.resolve();dist=args.dist.resolve()
if out.exists() or dist.exists():raise SystemExit('Refusing to overwrite any existing output directory')
if ' ' in str(root)+str(out)+str(dist)+str(pipeline):raise SystemExit('Android build scripts require paths without spaces')
if args.jobs<1:raise SystemExit('jobs must be positive')
for name in ['common-nomount-userns','.source_date_epoch_dir']:
 dest=pipeline/name
 if not dest.exists():dest.symlink_to(os.path.relpath(root/'kernel',pipeline))
 if dest.resolve()!=root/'kernel':raise SystemExit('Pipeline points to a different kernel export')
version=subprocess.check_output([str(pipeline/'prebuilts/clang/host/linux-x86/clang-r450784e/bin/clang'),'--version'],text=True)
if not all(v in version for v in ['8508608','r450784e','14.0.7']):raise SystemExit('Wrong compiler')
out.mkdir(parents=True);dist.mkdir(parents=True)
env=os.environ.copy()
for key in ['BUILD_NUMBER','FAST_BUILD','LTO','KASAN','KCSAN','SKIP_DEFCONFIG','SKIP_MRPROPER']:env.pop(key,None)
env.update(KERNEL_DIR='common-nomount-userns',BUILD_CONFIG=os.path.relpath(root/'configs/build.config.archive',pipeline),OUT_DIR=str(out),DIST_DIR=str(dist),SOURCE_DATE_EPOCH='1746772579',GIT_CONFIG_GLOBAL='/dev/null',GIT_CONFIG_NOSYSTEM='1',GIT_OPTIONAL_LOCKS='0')
metadata={'source_commit':'90700ba133db2fb1d2b05519d45de38ad3d148e1','compiler':version,'started_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'exit_code':None,'device_tested':False,'signing':'fresh local keys generated by Kbuild; never publish the output certs directory'}
log=dist/'build.log'
with log.open('w') as f:result=subprocess.run(['bash','build/build.sh',f'-j{args.jobs}'],cwd=pipeline,env=env,stdout=f,stderr=subprocess.STDOUT)
metadata['exit_code']=result.returncode
# Logs and debug files may contain the caller's paths; this directory is local-only.
metadata['artifacts']={}
for f in sorted(dist.iterdir()):
 if f.is_file() and f.name!='BUILD-INFO.json':
  with f.open('rb') as fd:metadata['artifacts'][f.name]=hashlib.file_digest(fd,'sha256').hexdigest()
(dist/'BUILD-INFO.json').write_text(json.dumps(metadata,indent=2)+'\n')
(dist/'DO-NOT-FLASH.txt').write_text('Raw GKI outputs. Matching vendor modules and OEM-specific verified packaging required. No device validation.\n')
print('Build exit:',result.returncode,'; outputs remain local and require a privacy review before distribution.')
raise SystemExit(result.returncode)
